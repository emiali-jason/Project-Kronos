def observed_panel(role, timeframe, subject, venue, day=None, start=None, end=None, currency=None, series=None):
    return dict(temporal_context=None, role=role, timeframe=timeframe, observed_subject=subject, venue=venue,
        observed_series=series, currency=currency, unit=None, trading_date=day,
        session=("REGULAR" if venue=="MCX" else "CONTINUOUS_TRADING") if day else None, timezone="Asia/Kolkata" if day else None,
        candle_start=f"{day}T{start}:00+05:30" if day else None,
        candle_end=f"{day}T{end}:00+05:30" if day else None,
        completion="COMPLETE" if day else None,
        captured_at="2026-08-28T10:16:00+05:30",
        latest_visible_end=f"{day}T{end}:00+05:30" if day else None,
        entire_panel_observed=True, opinion_overlays_present=False,
        content=[[key,"EXACT"] for key in CORE_CONTENT])


def fresh(tmp_path, symbol=LABELS[0][0], label=LABELS[0][1], *, payload=None):
    *_, mapping = _opening_inputs(subject=symbol)
    run, app = _application(tmp_path, mapping)
    app._clock=lambda: datetime.fromisoformat("2026-08-28T10:16:00+05:30")
    app._chart_input.clock=app._clock
    app._transport=IntradayReviewV2Transport(question_outbox=tmp_path/'questions', answer_inbox=tmp_path/'answers')
    app._visual_identity_resolver=load_visual_identity_resolver(publication_version="1.5.0")
    app._chart_input.resolver=app._visual_identity_resolver
    configure_fixture_calendar(app)
    cycle=app.create_eligible_cycles(run)[0]
    chart=app.upload_chart(cycle.cycle_identity, media_type="image/png", payload=_png(79) if payload is None else payload)
    assert app.review_store.load_chart_input(chart) is None
    result=app.create_individual_question_transport(cycle.cycle_identity)
    doc=json.loads(result.answer_template_path.read_bytes())
    answer=nse_document(result.packs[0]); answer['observed_visible_subject_identity']=label
    for item in answer['answers']:
        if item['question_id'] in {'Q6','Q9'}:
            item.update(observation_status="UNAVAILABLE",answer=None,visible_timeframes=[],visible_basis=None,
                        status_detail="No machine-selected single governed anchor.")
    answer['global_observation_status']='PARTIAL'
    header=template(result.packs[0])
    for row,(frame,day,start,end) in zip(header['panels'],ENDPOINTS,strict=True):
        row.update(panel_state="PRESENT",right_edge="EXACT",observed=observed_panel('NATIVE',frame,label,'NSE',day,start,end))
    answer[FIELD]=header;doc['candidates']=[answer]
    return app,cycle,chart,result,doc


def submit(app,cycle,result,doc):
    app._transport.answer_inbox.mkdir(exist_ok=True)
    (app._transport.answer_inbox/result.transport.expected_answer_filename).write_text(json.dumps(doc))
    return app.import_expected_answer(cycle.cycle_identity)


def snapshot(root):
    return {str(p.relative_to(root)):sha256(p.read_bytes()).hexdigest() for p in root.rglob('*') if p.is_file()}


@pytest.mark.parametrize('symbol,label',LABELS)
def test_fresh_sponsor_workflow_retains_receipt_and_replays(tmp_path,symbol,label):
    app,cycle,chart,result,doc=fresh(tmp_path,symbol,label)
    assert [p.suffix for p in app._transport.question_outbox.iterdir()]==['.pdf']
    assert app.review_store.load_chart_input(chart) is None
    # Read-only prevalidation itself creates no receipt or import.
    before=snapshot(app.review_store.root)
    assert app._prepare_transport_answer(result.transport,json.dumps(doc).encode()).validation.exact_match_count==1
    assert snapshot(app.review_store.root)==before
    outcome=submit(app,cycle,result,doc)
    assert (outcome.imported_count,outcome.rejected_count)==(1,0),outcome
    receipt=app.review_store.load_chart_input(chart)
    assert receipt.observation_source_identity.startswith('CHART-ANALYST-ANSWER-')
    evidence=app.review_store.load_visual_evidence_for_pack(result.packs[0].review_pack_identity)
    assert evidence.visual_identity_publication_version=='1.5.0'
    assert evidence.observed_visible_subject_identity==label
    parsed=parse_answer_pack(json.dumps(doc['candidates'][0]).encode())
    assert answer_artifact_from_bytes(answer_artifact_bytes(parsed))==parsed
    frozen=snapshot(app.review_store.root)
    assert submit(app,cycle,result,doc).already_imported_count==1
    assert snapshot(app.review_store.root)==frozen
    from kronos.intraday.review_v2_persistence import IntradayReviewV2Store
    restored=IntradayReviewV2Store(app.review_store.root)
    assert observation_bytes(restored.load_chart_input(chart))==observation_bytes(receipt)
    assert restored.load_visual_evidence_for_pack(evidence.review_pack_identity)==evidence


@pytest.mark.parametrize('mutation',[
    'subject','timeframe','missing','cropped_identity','cropped_time_axis','right_edge',
    'loading','unreadable','future','forming','wrong_revision','wrong_cycle','wrong_pack',
    'role_swap','no_endpoint','no_header','opinion','partial_panel','duplicate','unknown_key'])
def test_wrong_or_unprovable_answer_never_retains_receipt(tmp_path,mutation):
    app,cycle,chart,result,doc=fresh(tmp_path)
    answer=doc['candidates'][0];h=answer[FIELD];row=h['panels'][-1];p=row['observed']
    if mutation=='subject':p['observed_subject']='Nifty Bank Index'
    elif mutation=='timeframe':p['timeframe']='4H'
    elif mutation=='missing':row['panel_state']='ABSENT';p['timeframe']=None
    elif mutation.startswith('cropped_'):
        target='identity' if mutation=='cropped_identity' else 'time_axis'
        p['content']=[[k,'NOT_VISIBLE' if k==target else v] for k,v in p['content']]
    elif mutation=='right_edge':row['right_edge']='NOT_VISIBLE'
    elif mutation=='loading':row['panel_state']='LOADING'
    elif mutation=='unreadable':row['panel_state']='UNREADABLE'
    elif mutation=='future':p['latest_visible_end']='2026-08-28T10:20:00+05:30'
    elif mutation=='forming':p['completion']='INCOMPLETE'
    elif mutation=='wrong_revision':h['chart_binding_identity']='FOREIGN'
    elif mutation=='wrong_cycle':h['review_cycle_identity']='FOREIGN'
    elif mutation=='wrong_pack':h['review_pack_identity']='FOREIGN'
    elif mutation=='role_swap':p['role']='REFERENCE'
    elif mutation=='no_endpoint':p['candle_end']=None
    elif mutation=='no_header':answer.pop(FIELD)
    elif mutation=='opinion':p['opinion_overlays_present']=True
    elif mutation=='partial_panel':p['entire_panel_observed']=False
    elif mutation=='duplicate':h['panels'][-1]=h['panels'][0]
    else:p['expected_end']='COPY_FORBIDDEN'
    result_import=submit(app,cycle,result,doc)
    assert (result_import.imported_count,result_import.rejected_count)==(0,1),result_import
    assert app.review_store.load_chart_input(chart) is None
    assert app.review_store.load_visual_evidence_for_pack(result.packs[0].review_pack_identity) is None


def test_template_keeps_machine_orientation_out_of_observations(tmp_path):
    app,cycle,chart,result,doc=fresh(tmp_path)
    t=json.loads(result.answer_template_path.read_bytes())['candidates'][0][FIELD]
