def test_receipt_write_then_answer_failure_is_immutable_retryable(tmp_path,monkeypatch):
    app,cycle,chart,result,doc=fresh(tmp_path)
    from kronos.intraday.review import ReviewFailure
    original=app.review_store.retain_visual_evidence
    def fail(*args):raise ReviewError(ReviewFailure.INTEGRITY_INVALID)
    monkeypatch.setattr(app.review_store,'retain_visual_evidence',fail)
    assert submit(app,cycle,result,doc).imported_count==0
    retained=app.review_store.load_chart_input(chart)
    assert retained is not None
    assert app.review_store.load_visual_evidence_for_pack(result.packs[0].review_pack_identity) is None
    monkeypatch.setattr(app.review_store,'retain_visual_evidence',original)
